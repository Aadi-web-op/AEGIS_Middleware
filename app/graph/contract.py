"""The decision-graph trace contract, in one place.

Status: this mirrors the vocabulary written down in "Aegis Decision Graph
(Neo4j Add-on): Team Brief" (22 Oct 2026). Nothing matching it exists in
the repository yet, so it is **not** a confirmed contract -- Aaradhya owns
it. Everything the graph writer needs to know about the shape of a trace
is gathered here so that, when the real contract lands, one file changes.

Trace shape
-----------
    {
      "request_id": "<opaque id, also the Decision's identity>",
      "decision":   "ANSWER" | "CAVEAT" | "ESCALATE" | "ABSTAIN",
      "headline":   "<one-line explanation for the UI>",
      "nodes":      [ {"id": ..., "type": <node type>, ...props} ],
      "edges":      [ {"type": <rel type>, "from": <node id>,
                       "to": <node id>, ...props} ],
      "reasons":    [ {"code": ..., "message": ...} ]
    }

Identity
--------
A Decision is identified by `request_id` alone (team brief, rule 3).
Every other node carries its own `id`, generated by whoever builds the
trace, and the graph writer merges on `(label, id)`. Identity generation
deliberately lives in the trace builder, where it is reviewable, rather
than inside Cypher.

`reasons` is the UI's flat copy. The graph writer only ever persists what
appears in `nodes`/`edges`; it does not turn a top-level reason into a
node, because inventing graph structure is the trace builder's job, not
the writer's.
"""

from __future__ import annotations

from typing import Any, Dict, Iterable, List, Mapping, Tuple

# ---------------------------------------------------------------------------
# Vocabulary. These are the only identifiers ever interpolated into Cypher,
# which is why they are a closed set rather than anything taken from a trace.
# ---------------------------------------------------------------------------
NODE_TYPES: Tuple[str, ...] = ("Decision", "Claim", "Evidence", "Document", "Reason")

RELATIONSHIP_TYPES: Tuple[str, ...] = (
    "HAS_CLAIM",        # Decision  -> Claim
    "SUPPORTED_BY",     # Claim     -> Evidence
    "CONTRADICTED_BY",  # Claim     -> Evidence
    "FROM",             # Evidence  -> Document
    "CONFLICTS_WITH",   # Evidence  -> Evidence
    "SUPERSEDES",       # Document  -> Document
    "BECAUSE",          # Decision  -> Reason
    "ABOUT",            # Reason    -> Claim | Evidence
)

# "statement" is an NLI-level disagreement with no scalar value to compare.
CONFLICT_KINDS: Tuple[str, ...] = ("numeric", "date", "statement", "version")

DECISIONS: Tuple[str, ...] = ("ANSWER", "CAVEAT", "ESCALATE", "ABSTAIN")

# Team brief, rule 6. Enforced by the writer on every stored preview.
EVIDENCE_PREVIEW_CHARS = 120

# Rule 7: full retrieved document text is never persisted. These keys are
# dropped from Evidence and Document nodes rather than truncated, so that a
# future trace field cannot smuggle a whole passage into the graph.
RETRIEVED_TEXT_KEYS: Tuple[str, ...] = (
    "text",
    "full_text",
    "fulltext",
    "content",
    "passage",
    "body",
    "raw",
    "raw_text",
    "chunk_text",
    "document_text",
    "page_content",
)

# A Claim's text comes from the AI's own answer, not from a retrieved
# document, so it is stored -- capped to the same limit the claim extractor
# already applies (app.core.claims.MAX_CLAIM_CHARS).
CLAIM_TEXT_CHARS = 300

_NODE_TYPE_SET = frozenset(NODE_TYPES)
_REL_TYPE_SET = frozenset(RELATIONSHIP_TYPES)


class TraceContractError(ValueError):
    """A trace does not satisfy the contract and must not be written."""


def _require_mapping(value: Any, what: str) -> Mapping[str, Any]:
    if not isinstance(value, Mapping):
        raise TraceContractError(f"{what} must be a mapping, got {type(value).__name__}")
    return value


def _require_list(value: Any, what: str) -> List[Any]:
    if value is None:
        return []
    if not isinstance(value, (list, tuple)):
        raise TraceContractError(f"{what} must be a list, got {type(value).__name__}")
    return list(value)


def validate_trace(trace: Any) -> Dict[str, Any]:
    """Check a trace against the contract and return it normalised.

    Raises `TraceContractError` on anything the writer cannot store
    safely: a missing `request_id`, an unknown node label or relationship
    type, a node without an id, or an edge whose endpoints are not in the
    trace. Rejecting is the point -- a malformed trace must fail loudly
    here, where the caller swallows and logs it, rather than reach Cypher.
    """
    trace = _require_mapping(trace, "trace")

    request_id = trace.get("request_id")
    if not isinstance(request_id, str) or not request_id.strip():
        raise TraceContractError("trace.request_id must be a non-empty string")

    decision = trace.get("decision")
    if decision is not None and decision not in DECISIONS:
        raise TraceContractError(
            f"trace.decision {decision!r} is not one of {DECISIONS}"
        )

    nodes = _require_list(trace.get("nodes"), "trace.nodes")
    edges = _require_list(trace.get("edges"), "trace.edges")

    seen_ids: Dict[str, str] = {}
    clean_nodes: List[Dict[str, Any]] = []
    for position, node in enumerate(nodes):
        node = _require_mapping(node, f"trace.nodes[{position}]")
        node_type = node.get("type")
        if node_type not in _NODE_TYPE_SET:
            raise TraceContractError(
                f"trace.nodes[{position}].type {node_type!r} is not one of {NODE_TYPES}"
            )
        node_id = node.get("id")
        if not isinstance(node_id, str) or not node_id.strip():
            raise TraceContractError(
                f"trace.nodes[{position}].id must be a non-empty string"
            )
        if node_id in seen_ids and seen_ids[node_id] != node_type:
            raise TraceContractError(
                f"node id {node_id!r} is used for both {seen_ids[node_id]} and {node_type}"
            )
        seen_ids[node_id] = node_type
        clean_nodes.append(dict(node))

    clean_edges: List[Dict[str, Any]] = []
    for position, edge in enumerate(edges):
        edge = _require_mapping(edge, f"trace.edges[{position}]")
        rel_type = edge.get("type")
        if rel_type not in _REL_TYPE_SET:
            raise TraceContractError(
                f"trace.edges[{position}].type {rel_type!r} is not one of "
                f"{RELATIONSHIP_TYPES}"
            )
        source, target = edge.get("from"), edge.get("to")
        for end, label in ((source, "from"), (target, "to")):
            if not isinstance(end, str) or end not in seen_ids:
                raise TraceContractError(
                    f"trace.edges[{position}].{label} {end!r} is not a node in this trace"
                )
        kind = edge.get("kind")
        if kind is not None and kind not in CONFLICT_KINDS:
            raise TraceContractError(
                f"trace.edges[{position}].kind {kind!r} is not one of {CONFLICT_KINDS}"
            )
        clean_edges.append(dict(edge))

    return {
        "request_id": request_id,
        "decision": decision,
        "headline": trace.get("headline"),
        "nodes": clean_nodes,
        "edges": clean_edges,
        "reasons": _require_list(trace.get("reasons"), "trace.reasons"),
    }


def is_node_type(value: Any) -> bool:
    """True when `value` is an allow-listed node label."""
    return value in _NODE_TYPE_SET


def is_relationship_type(value: Any) -> bool:
    """True when `value` is an allow-listed relationship type."""
    return value in _REL_TYPE_SET


def truncate_preview(text: Any, limit: int = EVIDENCE_PREVIEW_CHARS) -> str:
    """Collapse whitespace and cut to `limit` characters."""
    collapsed = " ".join(str(text).split())
    return collapsed[:limit]


def strip_retrieved_text(props: Mapping[str, Any]) -> Tuple[Dict[str, Any], List[str]]:
    """Drop any key that could carry full retrieved document text.

    Returns the surviving properties and the names of the dropped keys, so
    the caller can log what it refused to persist.
    """
    dropped: List[str] = []
    kept: Dict[str, Any] = {}
    for key, value in props.items():
        if key.lower() in RETRIEVED_TEXT_KEYS:
            dropped.append(key)
            continue
        kept[key] = value
    return kept, dropped


def preview_keys(props: Iterable[str]) -> List[str]:
    """Property names that hold a preview and must respect the 120-char cap."""
    return [k for k in props if k == "preview" or k.endswith("_preview")]
