def test_rag_workflow_freshness_integration():
    kb = KnowledgeBase()
    # Add chunks with date 80 days ago
    stale_date_str = (date.today() - timedelta(days=80)).isoformat()
    chunks = chunk_text(
        text="The company health insurance coverage limit is 5000 dollars. " * 15,
        source="insurance_old.pdf",
        chunk_size=30,
        overlap=5,
        date=stale_date_str,
        version="v1",
    )
    kb.vector_store.add_chunks(chunks)

    provider = FakeProvider(["The company health insurance coverage limit is 5000 dollars."])
    evaluator = make_evaluator_with_freshness()
    workflow = AEGISWorkflow(kb, provider, evaluator)

    # 1. Run time-sensitive query -> should caveat with STALE_EVIDENCE
    res_time_sensitive = workflow.run(
        question="What is the company health insurance limit?",
        time_sensitive=True,
    )
    assert res_time_sensitive.decision == Decision.CAVEAT
    assert res_time_sensitive.signals.freshness == pytest.approx(0.1111, abs=0.02)
    assert any(r.code == ReasonCode.STALE_EVIDENCE for r in res_time_sensitive.reasons)

    # 2. Run non-time-sensitive query -> should answer
    res_non_time_sensitive = workflow.run(
        question="What is the company health insurance limit?",
        time_sensitive=False,
    )
    assert res_non_time_sensitive.decision == Decision.ANSWER
    assert not any(r.code == ReasonCode.STALE_EVIDENCE for r in res_non_time_sensitive.reasons)


def test_api_evaluate_endpoint_with_freshness():
    evaluator = make_evaluator_with_freshness()
    app = create_app(evaluator=evaluator)
    client = TestClient(app)

    # Post evaluate with stale evidence on time-sensitive query
    stale_date = (date.today() - timedelta(days=75)).isoformat()
    payload = {
        "query": "What is the updated interest rate?",
        "answer": "The interest rate is 4.5%.",
        "evidence": [{
            "text": "The interest rate is 4.5%.",
            "source": "rate_sheet.pdf",
            "date": stale_date,
        }],
        "profile": "standard",
        "time_sensitive": True,
    }
    res = client.post("/v1/evaluate", json=payload)
    assert res.status_code == 200
    body = res.json()
    assert body["decision"] == "CAVEAT"
    assert body["recommended_action"] == "return_with_caveat"
    assert body["signals"]["freshness"] < 0.40
    codes = [r["code"] for r in body["reasons"]]
    assert "STALE_EVIDENCE" in codes
