def test_integration_mixed_dates_recent_and_older():
    evaluator = make_evaluator_with_freshness()
    today = date.today()
    # Mixed: one today (0 days old) and one 20 days old -> average age 10 days
    # Freshness: 1.0 - (10 / 90) = 0.8889 -> well above 0.40 threshold
    req = EvaluateRequest(
        query="What are the vacation and sick leave policies?",
        answer="Vacation is 15 days, sick leave is 10 days.",
        evidence=[
            EvidenceItem(
                text="Vacation entitlement is 15 days.",
                source="new_vacation.pdf",
                date=today,
            ),
            EvidenceItem(
                text="Sick leave entitlement is 10 days.",
                source="sick_leave_policy.pdf",
                date=today - timedelta(days=20),
            ),
        ],
        profile="standard",
        time_sensitive=True,
    )
    resp = evaluator.evaluate(req)

    assert resp.decision == Decision.ANSWER
    assert resp.signals.freshness == pytest.approx(0.8889, abs=0.01)
    assert not any(r.code == ReasonCode.STALE_EVIDENCE for r in resp.reasons)


