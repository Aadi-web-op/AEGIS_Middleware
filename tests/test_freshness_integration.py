def make_evaluator_with_freshness(**other_signals):
    """Create an Evaluator backed by the real FreshnessSignal and stubs for other signals."""
    default_others = {
        "relevance": 0.95,
        "entailment": 0.95,
        "contradiction": 0.02,
        "completeness": 0.95,
        "ambiguity": 0.05,
    }
    default_others.update(other_signals)
    signals = [
        FixedSignal(name, val)
        for name, val in default_others.items()
    ]
    signals.append(FreshnessSignal())
    return Evaluator(signals, config=load_policy_config())


def test_integration_recent_evidence_gives_answer():
    evaluator = make_evaluator_with_freshness()
    today = date.today()
    req = EvaluateRequest(
        query="What is the remote work policy?",
        answer="Employees can work remotely 2 days a week.",
        evidence=[
            EvidenceItem(
                text="Employees are permitted up to 2 days remote work per week.",
                source="handbook_2026.pdf",
                date=today,
                version="v2",
            )
        ],
        profile="standard",
        time_sensitive=True,
    )
    resp = evaluator.evaluate(req)

    assert resp.decision == Decision.ANSWER
    assert resp.recommended_action == RecommendedAction.RETURN_ANSWER
    assert resp.signals.freshness == 1.0
    assert not any(r.code == ReasonCode.STALE_EVIDENCE for r in resp.reasons)
    assert not any(r.code == ReasonCode.SIGNAL_UNAVAILABLE for r in resp.reasons)


def test_integration_outdated_evidence_time_sensitive_caveats():
    evaluator = make_evaluator_with_freshness()
    # 70 days old -> freshness is 1.0 - (70 / 90) = 0.2222, which is < 0.40 caveat threshold
    stale_date = date.today() - timedelta(days=70)
    req = EvaluateRequest(
        query="What is the current baggage allowance?",
        answer="The allowance is 20kg per passenger.",
        evidence=[
            EvidenceItem(
                text="The baggage allowance is 20kg.",
                source="old_policy.pdf",
                date=stale_date,
            )
        ],
        profile="standard",
        time_sensitive=True,
    )
    resp = evaluator.evaluate(req)

    assert resp.decision == Decision.CAVEAT
    assert resp.recommended_action == RecommendedAction.RETURN_WITH_CAVEAT
    assert resp.signals.freshness == pytest.approx(0.2222, abs=0.01)
    reasons = [r.code for r in resp.reasons]
    assert ReasonCode.STALE_EVIDENCE in reasons
    assert resp.caveat_text is not None


def test_integration_outdated_evidence_non_time_sensitive_answers():
    evaluator = make_evaluator_with_freshness()
